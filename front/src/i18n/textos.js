// Traduce `texto` (en espanol) al idioma pedido y reemplaza {variables}.
export function traducir(idioma, texto, variables) {
  let salida = idioma === 'en' ? (EN[texto] ?? texto) : texto;
  if (variables) salida = salida.replace(/\{(\w+)\}/g, (_, clave) => (variables[clave] ?? '').toString());
  return salida;
}
